/// The FIDE federation for a Chess.com country code, when known.
pub fn fide_federation(country: &str) -> Option<&'static str> {
    let code = country.trim().to_ascii_uppercase();
    MAP.iter().find(|(iso, _)| *iso == code).map(|(_, fed)| *fed)
}

/// The country code at the end of a Chess.com country URL (`.../pub/country/US`).
pub fn code_from_url(url: &str) -> &str {
    url.rsplit('/').next().unwrap_or("")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn maps_codes() {
        assert_eq!(fide_federation("US"), Some("USA"));
        assert_eq!(fide_federation("de"), Some("GER"));
        assert_eq!(fide_federation("XE"), Some("ENG"));
        assert_eq!(fide_federation("XX"), None);
        assert_eq!(code_from_url("https://api.chess.com/pub/country/NO"), "NO");
    }
}
